void rf_test(void)
{
    status_t status;

    rf_driver_t *rf =
        rf_driver_get_instance();

    rf_hal_t hal = {0};

    rf_stm32_config_t config = {
        .timer = &htim3,
        .channel = TIM_CHANNEL_1,
        .data_port = GPIOA,
        .data_pin = GPIO_PIN_6
    };

    status = rf_stm32_init(
        &hal,
        &config);

    if (status != STATUS_OK)
    {
        printf("RF STM32 init failed: %d\r\n", status);
        return;
    }

    status = rf_driver_init(
        rf,
        &hal);

    if (status != STATUS_OK)
    {
        printf("RF driver init failed: %d\r\n", status);
        return;
    }

    status = rf_driver_receive_start(rf);

    if (status != STATUS_OK)
    {
        printf("RF receive start failed: %d\r\n", status);
        return;
    }

    printf("RF receiver started\r\n");

    /*
     * Temporary test.
     * Read after a short capture period.
     */
    HAL_Delay(200);

    rf_driver_receive_stop(rf);

    uint32_t count = 0U;

    status = rf_driver_receive_read(
        rf,
        pulses,
        RF_STM32_MAX_PULSES,
        &count);

    if (status != STATUS_OK)
    {
        printf("RF receive read failed: %d\r\n", status);
        return;
    }

    printf("Pulse count: %lu\r\n",
           (unsigned long)count);

    for (uint32_t i = 0U; i < count; i++)
    {
        printf(
            "%03lu: %s %u us\r\n",
            (unsigned long)i,
            pulses[i].level ? "HIGH" : "LOW",
            pulses[i].duration_us);
    }
}
